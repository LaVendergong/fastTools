export const PLATFORMS = [
  { id: 'win', name: 'Windows', pm: 'winget' },
  { id: 'mac', name: 'macOS', pm: 'Homebrew' },
  { id: 'linux', name: 'Linux', pm: 'apt' },
]

export function commandOf(tool, platform) {
  if (platform === 'win') {
    return tool.winget ? `winget install -e --id ${tool.winget}` : ''
  }
  if (platform === 'mac') {
    if (!tool.brew) return ''
    return tool.brew.startsWith('--cask') ? `brew install ${tool.brew}` : `brew install ${tool.brew}`
  }
  return tool.apt ? `sudo apt install -y ${tool.apt}` : ''
}
